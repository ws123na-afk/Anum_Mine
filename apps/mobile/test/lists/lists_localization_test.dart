final _placeholder = RegExp(r'\{[a-z]+\}');

void main() {
  test('English and Arabic cover the list screens', () {
    const en = AnumLocalizations(Locale('en'));
    const ar = AnumLocalizations(Locale('ar'));
    for (final key in _keys) {
      expect(en.t(key), isNot(key), reason: key);
      expect(ar.t(key), isNot(en.t(key)), reason: key);
      expect(RegExp(r'[\u0600-\u06FF]').hasMatch(ar.t(key)), isTrue,
          reason: key);
      expect(_placeholder.allMatches(ar.t(key)).map((m) => m[0]).toSet(),
          _placeholder.allMatches(en.t(key)).map((m) => m[0]).toSet(),
          reason: key);
    }
  });
}

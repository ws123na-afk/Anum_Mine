  /// "7 h 05 min" for a number of seconds.
  String hours(int seconds) {
    final minutes = (seconds / 60).round();
    return t('hours', {
      'h': minutes ~/ 60,
      'm': (minutes % 60).toString().padLeft(2, '0'),
    });
  }

